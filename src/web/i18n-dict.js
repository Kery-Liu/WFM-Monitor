  function fmt(tpl, args) {
    return String(tpl).replace(/\{(\d+)\}/g, (m, i) => (args[Number(i) - 1] == null ? m : String(args[Number(i) - 1])));
  }

  /** 中文原文 -> 目标语言；找不到就原样返回 */
  function translate(source, lang, depth = 0) {
    if (!source) return source;
    const key = String(source).trim();
    if (lang !== 'en') return source;
    if (Object.prototype.hasOwnProperty.call(DICT, key)) return fmt(DICT[key], []);
    for (const [re, rep] of RULES) {
      const m = key.match(re);
      if (m) {
        const out = typeof rep === 'function' ? rep(m) : fmt(rep, m.slice(1));
        // 组合文案（如 "最后更新 0 秒前"）需要再翻一层
        return depth < 2 ? translate(out, lang, depth + 1) : out;
      }
    }
    return source;
  }

